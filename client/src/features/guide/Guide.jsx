function normalize(value) {
  return value.toLocaleLowerCase('ru-RU').replace(/ё/g, 'е').trim()
}

export default function Guide() {
  const [query, setQuery] = useState('')
  const [activeSection, setActiveSection] = useState(SECTIONS[0].id)
  const sectionRefs = useRef({})

  const filteredSections = useMemo(() => {
    const normalizedQuery = normalize(query)
    if (!normalizedQuery) return SECTIONS

    return SECTIONS.filter((section) => {
      const searchableText = [
        section.title,
        section.description,
        ...section.keywords,
        ...section.steps.flatMap((step) => [step.title, step.text]),
        section.note?.title || '',
        section.note?.text || '',
      ].join(' ')

      return normalize(searchableText).includes(normalizedQuery)
    })
  }, [query])

  useEffect(() => {
    if (!filteredSections.some((section) => section.id === activeSection)) {
      setActiveSection(filteredSections[0]?.id || '')
    }
  }, [filteredSections, activeSection])

  useEffect(() => {
    if (typeof window === 'undefined' || !('IntersectionObserver' in window)) return undefined

    const observer = new IntersectionObserver(
      (entries) => {
        const visible = entries
          .filter((entry) => entry.isIntersecting)
          .sort((a, b) => a.boundingClientRect.top - b.boundingClientRect.top)

        if (visible[0]) setActiveSection(visible[0].target.id)
      },
      {
        rootMargin: '-12% 0px -72% 0px',
        threshold: 0,
      }
    )

    filteredSections.forEach((section) => {
      const element = sectionRefs.current[section.id]
      if (element) observer.observe(element)
    })

    return () => observer.disconnect()
  }, [filteredSections])

  const scrollToSection = (id) => {
    const element = sectionRefs.current[id]
    if (!element) return

    setActiveSection(id)
    element.scrollIntoView({
      behavior: window.matchMedia?.('(prefers-reduced-motion: reduce)').matches ? 'auto' : 'smooth',
      block: 'start',
    })
  }

  return (
    <div className={styles.page}>
      <header className={styles.header}>
        <div className={styles.headerInner}>
          <div className={styles.headerRow}>
            <div className={styles.headerCopy}>
              <h1 className={styles.title}>Руководство пользователя</h1>
              <p className={styles.subtitle}>
                Практические инструкции по работе с сотрудниками, нормами, выдачей и документами.
              </p>
            </div>
          </div>

          <div className={styles.searchWrap}>
            <Search size={19} className={styles.searchIcon} aria-hidden="true" />
            <input
              className={styles.searchInput}
              type="search"
              value={query}
              onChange={(event) => setQuery(event.target.value)}
              placeholder="Найти действие или раздел… Например, «добавить сотрудника»"
              aria-label="Поиск по руководству пользователя"
            />
            {query && (
              <button
                type="button"
                className={styles.clearSearch}
                onClick={() => setQuery('')}
                aria-label="Очистить поиск"
              >
                <X size={17} />
              </button>
            )}
          </div>
        </div>
      </header>

      <div className={styles.layout}>
        <aside className={styles.sidebar}>
          <div className={styles.sidebarHeading}>Содержание</div>
          <nav className={styles.sectionNav} aria-label="Разделы руководства">
            {filteredSections.map((section, index) => {
              const SectionIcon = section.icon
              const isActive = activeSection === section.id

              return (
                <button
                  key={section.id}
                  type="button"
                  className={`${styles.navItem} ${isActive ? styles.navItemActive : ''}`}
                  onClick={() => scrollToSection(section.id)}
                  aria-current={isActive ? 'location' : undefined}
                >
                  <span className={styles.navNumber}>{String(index + 1).padStart(2, '0')}</span>
                  <SectionIcon size={16} strokeWidth={1.8} className={styles.navIcon} />
                  <span className={styles.navLabel}>{section.title}</span>
                  <ArrowUpRight size={13} className={styles.navArrow} />
                </button>
              )
            })}
          </nav>
        </aside>

        <div className={styles.content}>
          {query && (
            <div className={styles.resultCaption} role="status">
              {filteredSections.length > 0
                ? `Найдено разделов: ${filteredSections.length}`
                : 'По вашему запросу ничего не найдено'}
            </div>
          )}


          {filteredSections.length === 0 ? (
            <div className={styles.emptySearch}>
              <div className={styles.emptyIcon}><Search size={23} /></div>
              <h2>Ничего не найдено</h2>
              <p>Попробуйте другое слово: «сертификат», «норма», «сотрудник» или «выдача».</p>
              <button type="button" className={styles.resetButton} onClick={() => setQuery('')}>
                Сбросить поиск
              </button>
            </div>
          ) : (
            <div className={styles.sections}>
              {filteredSections.map((section) => {
                const SectionIcon = section.icon

                return (
                  <section
                    key={section.id}
                    id={section.id}
                    ref={(element) => {
                      sectionRefs.current[section.id] = element
                    }}
                    className={styles.guideSection}
                    aria-labelledby={`${section.id}-title`}
                  >
                    <div className={styles.guideSectionHeader}>
                      <div className={styles.sectionIconWrap}>
                        <SectionIcon size={21} strokeWidth={1.8} />
                      </div>
                      <div className={styles.sectionHeading}>
                        <div className={styles.sectionEyebrow}>ИНСТРУКЦИЯ</div>
                        <h2 id={`${section.id}-title`}>{section.title}</h2>
                      </div>
                      <Link to={section.href} className={styles.openLink}>
                        <span>{section.hrefLabel}</span>
                        <ArrowUpRight size={16} />
                      </Link>
                    </div>

                    <p className={styles.sectionDescription}>{section.description}</p>

                    <ol className={styles.steps}>
                      {section.steps.map((step, index) => (
                        <li key={`${section.id}-${index}`} className={styles.step}>
                          <span className={styles.stepNumber}>{String(index + 1).padStart(2, '0')}</span>
                          <div className={styles.stepBody}>
                            <h3>{step.title}</h3>
                            <p>{step.text}</p>
                          </div>
                        </li>
                      ))}
                    </ol>

                    {section.note && (
                      <div
                        className={`${styles.note} ${section.note.type === 'warning' ? styles.noteWarning : styles.noteInfo}`}
                      >
                        <span className={styles.noteIcon}>
                          {section.note.type === 'warning' ? <AlertTriangle size={18} /> : <Info size={18} />}
                        </span>
                        <div>
                          <h3>{section.note.title}</h3>
                          <p>{section.note.text}</p>
                        </div>
                      </div>
                    )}
                  </section>
                )
              })}
            </div>
          )}
        </div>
      </div>
    </div>
  )
}
